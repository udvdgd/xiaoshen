def pbkdf2(password,salt,iters,dklen,hname='sha256'):
    prf=lambda p,s:hmac.new(p,s,getattr(hashlib,hname)).digest()
    hlen=hashlib.new(hname).digest_size; out=b''
    for i in range(1,(dklen+hlen-1)//hlen+1):
        U=prf(password,salt+struct.pack('>I',i)); T=U
        for _ in range(1,iters): U=prf(password,U); T=bytes(a^b for a,b in zip(T,U))
        out+=T
    return out[:dklen]

